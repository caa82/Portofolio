-- ----------------------------------------------------------
-- 1. TABEL: projects
-- Menampung seluruh data portofolio project, spesifikasi teknis,
-- arsitektur, tech stack, dan tautan dokumen / demo.
-- ----------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    category TEXT NOT NULL,
    year TEXT,
    role TEXT,
    client TEXT,
    summary TEXT,
    problem TEXT,
    solution TEXT,
    architecture TEXT,
    tech_stack TEXT[] DEFAULT '{}',
    image_url TEXT DEFAULT '',
    github_url TEXT DEFAULT '',
    demo_url TEXT DEFAULT '',
    doc_analysis_url TEXT DEFAULT '',
    document_url TEXT DEFAULT '',
    document_path TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- Aktifkan Row Level Security (RLS)
ALTER TABLE public.projects ENABLE ROW LEVEL SECURITY;

-- Policy: Izinkan siapa saja (publik / anon) membaca daftar project
CREATE POLICY "Allow public read access on projects"
ON public.projects
FOR SELECT
TO public
USING (true);


-- ----------------------------------------------------------
-- 2. TABEL: messages
-- Menampung pesan dari formulir kontak langsung di website
-- ----------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL,
    subject TEXT NOT NULL,
    message TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- Aktifkan Row Level Security (RLS)
ALTER TABLE public.messages ENABLE ROW LEVEL SECURITY;

-- Policy: Izinkan pengunjung web (anonim) mengirim pesan
CREATE POLICY "Allow public insert on messages"
ON public.messages
FOR INSERT
TO public
WITH CHECK (true);

-- Policy: Hanya user terautentikasi (admin/owner) yang bisa membaca pesan
CREATE POLICY "Allow authenticated read on messages"
ON public.messages
FOR SELECT
TO authenticated
USING (true);


-- ----------------------------------------------------------
-- 3. STORAGE BUCKET: project-docs
-- Bucket untuk upload berkas dokumen PDF / cover project
-- ----------------------------------------------------------
INSERT INTO storage.buckets (id, name, public)
VALUES ('project-docs', 'project-docs', true)
ON CONFLICT (id) DO NOTHING;

-- Policy Storage: Izinkan publik mengunduh/melihat dokumen project
CREATE POLICY "Allow public read on project-docs"
ON storage.objects
FOR SELECT
TO public
USING (bucket_id = 'project-docs');


